TOTAL = 2000


def build_body(openers, mids, closers):
    n = random.choices([1, 2, 3], weights=[25, 45, 30])[0]  # 中间句数量
    idx = random.randrange(len(openers))
    parts = [openers[idx]]
    parts.extend(random.sample(mids, n))
    parts.append(random.choice(closers))
    if n >= 2 and random.random() < 0.45:
        # 分段：读起来更像人写的（只用一个换行，避免和「空行分条」的格式冲突）
        cut = random.randint(1, len(parts) - 1)
        return "".join(parts[:cut]) + "\n" + "".join(parts[cut:]), idx
    return "".join(parts), idx


def main():
    names = list(POOLS)
    items = []
    seen_body = set()
    seen_title = set()
    guard = 0
    while len(items) < TOTAL and guard < TOTAL * 80:
        guard += 1
        name = names[len(items) % len(names)]
        pool = POOLS[name]
        body, opener_idx = build_body(pool["open"], pool["mid"], pool["close"])
        if body in seen_body:
            continue
        stem = OPEN_TITLES[name][opener_idx]
        suffix = random.choice(SUFFIXES)
        title = (stem + suffix).strip()
        if len(title) > 30:
            title = title[:30]
        if len(title) < 5:
            title = (title + "｜随笔").lstrip("｜")[:30]
        if title in seen_title:
            continue
        seen_body.add(body)
        seen_title.add(title)
        items.append({"title": title, "body": body, "category": name})

    random.shuffle(items)

    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(here, "presets")
    os.makedirs(out_dir, exist_ok=True)

    json_path = os.path.join(out_dir, "正能量预置内容2000.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump({"version": 1, "mode": "preset", "items": items}, f, ensure_ascii=False, indent=2)

